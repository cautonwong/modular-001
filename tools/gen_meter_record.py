#!/usr/bin/env python3
"""Generate the target-internal meter record layout header.

The legacy aggregate root is the source of truth. This script preprocesses
kernel/legacy_control_block.h, reads the expanded struct, and emits one
constant-expression macro per field for offsets and sizes. Callers stop
spelling offsetof() and sizeof() themselves.

Usage:
    tools/gen_meter_record.py            # write the header
    tools/gen_meter_record.py --check    # fail if the header is stale
"""

from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "targets" / "stategrid_meter" / "persistence" / "meter_record.h"
STRUCT = "mbase_control_block_t"
INCLUDES = [
    "-I",
    str(ROOT),
    "-I",
    str(ROOT / "nidavellir" / "include"),
    "-I",
    str(ROOT / "targets" / "stategrid_meter"),
    "-I",
    str(ROOT / "targets" / "stategrid_meter" / "app"),
]


def preprocess():
    with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as source:
        source.write('#include "kernel/legacy_control_block.h"\n')
        path = source.name
    try:
        result = subprocess.run(
            ["gcc", "-E", "-P", *INCLUDES, path],
            check=True,
            capture_output=True,
            text=True,
        )
    finally:
        Path(path).unlink()
    return result.stdout


def struct_body(text):
    start = text.index("struct " + STRUCT)
    brace = text.index("{", start)
    depth = 0
    for index in range(brace, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[brace + 1:index]
    raise ValueError("unterminated struct " + STRUCT)


def declarations(body):
    items = []
    start = 0
    depth = 0
    for index, char in enumerate(body):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        elif char == ";" and depth == 0:
            items.append(" ".join(body[start:index].split()))
            start = index + 1
    return items


def parse_fields(body):
    fields = []
    names = set()
    for declaration in declarations(body):
        match = re.match(
            r"(?P<type>.+?)\s+(?P<name>[A-Za-z_]\w*)(?P<dims>(?:\[[^\]]+\])*)$",
            declaration,
        )
        if not match:
            raise ValueError("unparsed declaration: " + declaration)
        name = match.group("name")
        if name in names:
            raise ValueError("duplicate field: " + name)
        names.add(name)
        dims = re.findall(r"\[([^\]]+)\]", match.group("dims"))
        fields.append((match.group("type"), name, dims))
    return fields


def render(fields):
    lines = [
        "/*",
        " * Generated by tools/gen_meter_record.py from",
        " * nidavellir/include/kernel/legacy_control_block.h. Do not edit.",
        " *",
        " * Constant-expression macros keep the byte layout in one place while",
        " * remaining usable in static initializers and case labels.",
        " */",
        "#ifndef ND_TARGET_STATEGRID_METER_RECORD_H",
        "#define ND_TARGET_STATEGRID_METER_RECORD_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "kernel/legacy_control_block.h"',
        "",
        "#define nd_mbase_size() ((uint32_t)sizeof(struct %s))" % STRUCT,
        "",
    ]
    for type_name, name, dims in fields:
        lines.append(
            "#define nd_mbase_offset_%s() "
            "((uint32_t)offsetof(struct %s, %s))" % (name, STRUCT, name)
        )
        lines.append(
            "#define nd_mbase_size_%s() "
            "((uint32_t)sizeof(((struct %s *)0)->%s))" % (name, STRUCT, name)
        )
        if dims:
            lines.append(
                "#define nd_mbase_rows_%s() "
                "((uint32_t)(sizeof(((struct %s *)0)->%s) / "
                "sizeof(((struct %s *)0)->%s[0])))" % (name, STRUCT, name, STRUCT, name)
            )
        lines.append("#define nd_mbase_%s(m) ((m)->%s)" % (name, name))
        lines.append("")
    lines.append("#endif")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    fields = parse_fields(struct_body(preprocess()))
    rendered = render(fields)
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/gen_meter_record.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(fields)} fields")
    return 0


if __name__ == "__main__":
    sys.exit(main())

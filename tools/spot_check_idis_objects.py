#!/usr/bin/env python3
"""Sample object_model.csv rows and confirm them against the IDIS raw text."""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = os.path.join(ROOT, "docs/idis/object_model.csv")
RAW = os.path.join(
    ROOT, "docs/idis/IDIS-S03-001-objectmodelPack3Ed1.0-V3.txt")
OUT = os.path.join(ROOT, "docs/idis/object-spot-check.md")


def main():
    rows = list(csv.DictReader(open(MODEL, encoding="utf-8")))
    unique = []
    seen = set()
    for row in rows:
        key = (row["obis"], row["attr_index"])
        if key not in seen:
            seen.add(key)
            unique.append(row)
    step = max(1, len(unique) // 20)
    sample = unique[::step][:20]
    raw = open(RAW, encoding="utf-8").read()
    lines = []
    failed = 0
    for row in sample:
        obis = row["obis"]
        attr = row["attr_name"].strip()
        raw_lines = raw.splitlines()
        hit_indexes = [index for index, line in enumerate(raw_lines)
                       if obis in line]
        hits = [raw_lines[index] for index in hit_indexes]
        name_ok = bool(attr) and any(
            attr.split("[")[0] in raw_lines[index + offset]
            for index in hit_indexes
            for offset in range(0, 25)
            if index + offset < len(raw_lines))
        if not hits or not name_ok:
            failed += 1
        lines.append(
            f"| {obis} | {row['class']} | {row['attr_index']} | {attr} | "
            f"{'yes' if hits else 'no'} | {'yes' if name_ok else 'no'} |")
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("# IDIS object model spot check\n\n")
        out.write("Generated by `tools/spot_check_idis_objects.py`.\n\n")
        out.write("| OBIS | class | attr | name | raw hit | name hit |\n")
        out.write("|---|---:|---:|---|---|---|\n")
        out.write("\n".join(lines) + "\n")
    print(f"spot-checked {len(sample)} rows, {failed} without a raw hit")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
